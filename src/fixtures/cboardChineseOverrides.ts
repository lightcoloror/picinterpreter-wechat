export const CBOARD_CHINESE_SYNCHRONIZED_LABEL_KEYS = Array.from(
  new Set([
    ...Object.keys(TILE_LABEL_OVERRIDES),
    ...getCboardCommunicationConceptProfileLabelKeys()
  ])
)

export function resolveCboardChineseBoardName(board: {
  name: string
  nameKey?: string
}) {
  return BOARD_NAME_OVERRIDES[board.nameKey || ''] || board.name
}

export function resolveCboardChineseTileLabel(tile: {
  label: string
  labelKey?: string
}) {
  const labelKey = tile.labelKey || ''
  const conceptProfile = getCboardCommunicationConceptProfile(labelKey)
  return (
    TILE_LABEL_OVERRIDES[labelKey] ||
    (conceptProfile && conceptProfile.label) ||
    tile.label
  )
}
